// Writes each backend's mcp_bazaar_tools.json from the built tool registry:
// the paid (inline_x402) tools of that service, their input schema without
// transport-only args, and the Bazaar example from src/bazaarExamples.ts.
// The backends attach these declarations when they settle an MCP payment, so
// they must match what the MCP challenge advertises.
//
// Usage: npm run build && node scripts/gen_bazaar_manifests.mjs <out-dir>
// Writes <out-dir>/<service>.mcp_bazaar_tools.json; copy each into its repo.

import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { SERVICES } from "../dist/services/index.js";
import { mcpBazaarExtension, MCP_PUBLIC_URL } from "../dist/x402mcp.js";

const outDir = process.argv[2];
if (!outDir) {
  console.error("usage: node scripts/gen_bazaar_manifests.mjs <out-dir>");
  process.exit(2);
}
mkdirSync(outDir, { recursive: true });

for (const svc of SERVICES) {
  const tools = svc.tools
    .filter((t) => t.authMode === "inline_x402")
    .map((t) => {
      const input = mcpBazaarExtension(t).info.input;
      const entry = { toolName: t.name, description: t.description, inputSchema: input.inputSchema };
      if (input.example) entry.example = input.example;
      return entry;
    });
  if (!tools.length) continue;
  const manifest = {
    _comment:
      "Paid MCP tools on this service, registered as Coinbase Bazaar MCP entries. Generated by " +
      "xrpl-utilities-mcp scripts/gen_bazaar_manifests.mjs (inputSchema without payment_signature/" +
      "_bypass_key, plus the Bazaar example). Regenerate when a paid tool schema or example changes.",
    mcp_url: MCP_PUBLIC_URL,
    tools,
  };
  const path = resolve(join(outDir, `${svc.id}.mcp_bazaar_tools.json`));
  writeFileSync(path, JSON.stringify(manifest, null, 1) + "\n");
  console.log(`${svc.id}: ${tools.length} tool(s) -> ${path}`);
}
